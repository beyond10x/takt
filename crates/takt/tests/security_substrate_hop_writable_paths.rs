//! Security review of story:confinement-through-substrate-on-linux-and-macos, the Linux scoped
//! workspace: what a confined test command can write besides `target/`.
//!
//! The run's `target/` is writable and the tree's `.git` is not; a hard link made from `target/`
//! to a file of `.git` would make the read-only file writable through the writable mount. The run's
//! `HOME`, `/tmp` and `/dev/shm` are writable inside the run; a write there must not reach the
//! host. Each probe's outcome is written to `target/probe.txt`, read back here.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use takt::confinement::{self, Confinement as _, Substrate, TestRun};
use takt::validator::TestsRun;

struct Scratch(PathBuf);

impl Drop for Scratch {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

fn scratch(name: &str) -> Scratch {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR")).join(format!(
        "security-substrate-hop-{}-{name}",
        std::process::id()
    ));
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(&dir).expect("a scratch directory");
    Scratch(dir)
}

fn git(tree: &Path, args: &[&str]) -> String {
    let output = Command::new("git")
        .args(["-c", "user.name=t", "-c", "user.email=t@localhost"])
        .args(args)
        .current_dir(tree)
        .output()
        .expect("git runs");
    assert!(output.status.success(), "git {args:?}");
    String::from_utf8_lossy(&output.stdout).trim().to_owned()
}

fn repository(outer: &Path, files: &[(&str, String)]) -> PathBuf {
    let repo = outer.join("repo");
    fs::create_dir_all(&repo).expect("a directory");
    fs::write(repo.join(".gitignore"), "target/\n").expect("a file");
    for (path, text) in files {
        let at = repo.join(path);
        fs::create_dir_all(at.parent().expect("a parent")).expect("a directory");
        fs::write(&at, text).expect("a file");
    }
    git(&repo, &["init", "-q", "-b", "main"]);
    git(&repo, &["add", "-A"]);
    git(&repo, &["commit", "-q", "-m", "start"]);
    repo
}

const MANIFEST: &str =
    "[package]\nname = \"probe\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n[workspace]\n";

const LOCK: &str = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"probe\"\nversion = \"0.1.0\"\n";

/// The probe test: each attempt's outcome, `<name> ok` or `<name> err <error>`, one a line.
fn probe(marker: &str) -> String {
    format!(
        r#"
use std::io::Write as _;

fn attempt(out: &mut Vec<String>, name: &str, result: std::io::Result<()>) {{
    match result {{
        Ok(()) => out.push(format!("{{name}} ok")),
        Err(error) => out.push(format!("{{name}} err {{error}}")),
    }}
}}

#[test]
fn probes() {{
    let mut out = Vec::new();
    attempt(&mut out, "hardlink-head", std::fs::hard_link("/workspace/.git/HEAD", "/workspace/target/head-link"));
    attempt(&mut out, "hardlink-config", std::fs::hard_link("/workspace/.git/config", "/workspace/target/config-link"));
    attempt(&mut out, "write-head", std::fs::OpenOptions::new().append(true).open("/workspace/.git/HEAD").and_then(|mut f| f.write_all(b"x")));
    attempt(&mut out, "rename-target", std::fs::rename("/workspace/target", "/workspace/target-moved"));
    attempt(&mut out, "tmp", std::fs::write("/tmp/{marker}", "x"));
    attempt(&mut out, "dev-shm", std::fs::write("/dev/shm/{marker}", "x"));
    let home = std::env::var("HOME").unwrap_or_default();
    attempt(&mut out, "home", std::fs::write(format!("{{home}}/{marker}"), "x"));
    out.push(format!("home-is {{home}}"));
    std::fs::write("/workspace/target/probe.txt", out.join("\n")).expect("target is writable");
}}
"#
    )
}

/// A hard link from `target/` into `.git` is refused, `.git/HEAD` stays as it was, `target`
/// cannot be moved, and the run's `/tmp`, `/dev/shm` and `HOME` writes reach no host path.
#[test]
fn security_substrate_hop_writable_paths_reach_neither_git_nor_the_host() {
    if std::env::consts::OS != "linux" {
        return;
    }
    let outer = scratch("writable-paths");
    let marker = format!("takt-security-hop-{}", std::process::id());
    let repo = repository(
        &outer.0,
        &[
            ("Cargo.toml", MANIFEST.to_owned()),
            ("Cargo.lock", LOCK.to_owned()),
            ("src/lib.rs", probe(&marker)),
        ],
    );
    let adapter = match Substrate::open(&repo, &confinement::Options::default()) {
        Ok(adapter) => adapter,
        Err(error) => {
            eprintln!("skipped: missing prerequisite: {error:#}");
            return;
        }
    };
    eprintln!("adapter: {}", adapter.record().describe());
    let head = fs::read(repo.join(".git/HEAD")).expect("HEAD");
    let argv: Vec<String> = ["cargo", "test", "--quiet", "--offline"]
        .iter()
        .map(|arg| (*arg).to_owned())
        .collect();
    let finished = adapter
        .run_test(&TestRun {
            argv: &argv,
            tree: &repo,
            limits: TestsRun::LIMITS,
        })
        .expect("the confined test command runs");
    let report = fs::read_to_string(repo.join("target/probe.txt")).unwrap_or_else(|_| {
        panic!(
            "precondition: the probe wrote its report (exit {:?}): {}{}",
            finished.code,
            String::from_utf8_lossy(&finished.stdout),
            String::from_utf8_lossy(&finished.stderr)
        )
    });
    eprintln!("{report}");
    let mut leaked = Vec::new();
    for host in [
        PathBuf::from("/tmp").join(&marker),
        PathBuf::from("/dev/shm").join(&marker),
        std::env::temp_dir().join(&marker),
    ] {
        if host.exists() {
            let _ = fs::remove_file(&host);
            leaked.push(host);
        }
    }
    let line = |name: &str| {
        report
            .lines()
            .find(|line| line.starts_with(&format!("{name} ")))
            .unwrap_or_default()
            .to_owned()
    };
    for name in [
        "hardlink-head",
        "hardlink-config",
        "write-head",
        "rename-target",
    ] {
        assert!(
            line(name).starts_with(&format!("{name} err")),
            "a confined test command did {name}: {report}"
        );
    }
    assert_eq!(
        fs::read(repo.join(".git/HEAD")).expect("HEAD"),
        head,
        "{report}"
    );
    assert!(
        leaked.is_empty(),
        "the run's writes reached the host at {leaked:?}: {report}"
    );
}
