//! Security review of story:confinement-through-substrate-on-linux-and-macos, the Linux scoped
//! workspace: a confined test command writes only its tree's `target/`, and every write to the
//! tree's `.git` fails (M20, `Candidate::test_access`).
//!
//! The scratch directory each confined test command gets under `target/` is made by takt
//! itself, on the host and unconfined, before the run starts (`TestPlan::new`): it creates
//! `<scratch>/cargo-home` and links the cargo caches under it by path. The run's `CARGO_HOME`
//! shows its name to the test command, which may write `target/`. A test command that leaves a
//! relative symlink to the tree's `.git/refs/heads` at the names it expects the next confined
//! runs of the process to take (a setup command before the test command, or the test command of
//! a later step) must not lead takt to create anything there: the next scratch takes a name the
//! command could not predict, and an existing path at that name is an error, never followed.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use takt::confinement::{self, Confinement as _, Substrate, TestRun};
use takt::validator::TestsRun;

/// A scratch directory under this crate's build directory, removed on drop.
struct Scratch(PathBuf);

impl Drop for Scratch {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

fn scratch(name: &str) -> Scratch {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR")).join(format!(
        "security-substrate-hop-{}-{name}",
        std::process::id()
    ));
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(&dir).expect("a scratch directory");
    Scratch(dir)
}

fn git(tree: &Path, args: &[&str]) -> String {
    let output = Command::new("git")
        .args(["-c", "user.name=t", "-c", "user.email=t@localhost"])
        .args(args)
        .current_dir(tree)
        .output()
        .expect("git runs");
    assert!(output.status.success(), "git {args:?}");
    String::from_utf8_lossy(&output.stdout).trim().to_owned()
}

/// A repository at `outer/repo` holding `files` (path, text) in one commit.
fn repository(outer: &Path, files: &[(&str, &str)]) -> PathBuf {
    let repo = outer.join("repo");
    fs::create_dir_all(&repo).expect("a directory");
    fs::write(repo.join(".gitignore"), "target/\n").expect("a file");
    for (path, text) in files {
        let at = repo.join(path);
        fs::create_dir_all(at.parent().expect("a parent")).expect("a directory");
        fs::write(&at, text).expect("a file");
    }
    git(&repo, &["init", "-q", "-b", "main"]);
    git(&repo, &["add", "-A"]);
    git(&repo, &["commit", "-q", "-m", "start"]);
    repo
}

const MANIFEST: &str =
    "[package]\nname = \"probe\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n[workspace]\n";

const LOCK: &str = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"probe\"\nversion = \"0.1.0\"\n";

/// A test that reads its run's scratch directory from `CARGO_HOME` and leaves, at the names
/// the next sixteen runs of this process take, a relative symlink to the tree's
/// `.git/refs/heads`.
const PLANT: &str = r#"
#[test]
fn plants_the_next_scratch_names() {
    let home = std::env::var("CARGO_HOME").expect("the run's CARGO_HOME");
    let run = std::path::Path::new(&home).parent().expect("the run's scratch directory");
    let name = run.file_name().and_then(|name| name.to_str()).expect("its name");
    let (prefix, count) = name.rsplit_once('-').expect("takt-run-<pid>-<n>");
    let count: u64 = count.parse().expect("a number");
    let target = run.parent().expect("target");
    for next in 1..=16 {
        let at = target.join(format!("{prefix}-{}", count + next));
        std::os::unix::fs::symlink("../.git/refs/heads", &at).expect("target is writable");
    }
}
"#;

fn cargo_test() -> Vec<String> {
    ["cargo", "test", "--quiet", "--offline"]
        .iter()
        .map(|arg| (*arg).to_owned())
        .collect()
}

/// Two confined test commands in one process, as a setup command and the test command run: the
/// first leaves symlinks at the scratch names the next runs take, the second is any command.
/// After them the tree's `.git/refs/heads` holds only what it held before.
#[test]
fn security_substrate_hop_a_test_command_cannot_steer_the_next_scratch_into_git() {
    let outer = scratch("scratch-redirect");
    let repo = repository(
        &outer.0,
        &[
            ("Cargo.toml", MANIFEST),
            ("Cargo.lock", LOCK),
            ("src/lib.rs", PLANT),
        ],
    );
    let adapter = match Substrate::open(&repo, &confinement::Options::default()) {
        Ok(adapter) => adapter,
        Err(error) => {
            eprintln!("skipped: missing prerequisite: {error:#}");
            return;
        }
    };
    eprintln!("adapter: {}", adapter.record().describe());
    let heads_before: Vec<String> = fs::read_dir(repo.join(".git/refs/heads"))
        .expect("refs/heads")
        .map(|entry| {
            entry
                .expect("an entry")
                .file_name()
                .to_string_lossy()
                .into_owned()
        })
        .collect();

    let argv = cargo_test();
    let first = adapter
        .run_test(&TestRun {
            argv: &argv,
            tree: &repo,
            limits: TestsRun::LIMITS,
        })
        .expect("the first confined test command runs");
    let planted = fs::read_dir(repo.join("target"))
        .expect("target")
        .filter_map(Result::ok)
        .filter(|entry| entry.file_type().is_ok_and(|kind| kind.is_symlink()))
        .count();
    assert!(
        first.code == Some(0) && planted == 16,
        "precondition: the first run planted its symlinks in target/ (exit {:?}, {planted} planted): {}{}",
        first.code,
        String::from_utf8_lossy(&first.stdout),
        String::from_utf8_lossy(&first.stderr)
    );

    let second = adapter.run_test(&TestRun {
        argv: &argv,
        tree: &repo,
        limits: TestsRun::LIMITS,
    });
    eprintln!(
        "second run: {}",
        match &second {
            Ok(finished) => format!("exit {:?}", finished.code),
            Err(error) => format!("{error:#}"),
        }
    );

    let heads_after: Vec<String> = fs::read_dir(repo.join(".git/refs/heads"))
        .expect("refs/heads")
        .map(|entry| {
            entry
                .expect("an entry")
                .file_name()
                .to_string_lossy()
                .into_owned()
        })
        .collect();
    let refs = Command::new("git")
        .args(["for-each-ref"])
        .current_dir(&repo)
        .output()
        .expect("git runs");
    assert_eq!(
        heads_after,
        heads_before,
        "story:confinement-through-substrate-on-linux-and-macos: a confined test command steered takt's own scratch directory into the tree's .git/refs/heads; git for-each-ref now says: {}{}",
        String::from_utf8_lossy(&refs.stdout),
        String::from_utf8_lossy(&refs.stderr)
    );
}
