use std::fs;
use std::os::unix::fs::PermissionsExt as _;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};
use std::time::{Duration, Instant};

struct Scratch(PathBuf);

impl Drop for Scratch {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

fn scratch(name: &str) -> Scratch {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR"))
        .join(format!("security-substrate-{}-{name}", std::process::id()));
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(&dir).expect("a scratch directory");
    Scratch(dir)
}

fn git(tree: &Path, args: &[&str]) {
    let status = Command::new("git")
        .args(["-c", "user.name=t", "-c", "user.email=t@localhost"])
        .args(args)
        .current_dir(tree)
        .status()
        .expect("git runs");
    assert!(status.success(), "git {args:?}");
}

const PROBE_LOCK: &str = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"probe\"\nversion = \"0.1.0\"\n";

fn repository(outer: &Path, files: &[(&str, &str, bool)]) -> PathBuf {
    let repo = outer.join("repo");
    fs::create_dir_all(&repo).expect("a directory");
    fs::write(repo.join(".gitignore"), "target/\n").expect("a file");
    for (path, text, executable) in files {
        let at = repo.join(path);
        fs::create_dir_all(at.parent().expect("a parent")).expect("a directory");
        fs::write(&at, text).expect("a file");
        if *executable {
            fs::set_permissions(&at, fs::Permissions::from_mode(0o755)).expect("a mode");
        }
    }
    git(&repo, &["init", "-q", "-b", "main"]);
    git(&repo, &["add", "-A"]);
    git(&repo, &["commit", "-q", "-m", "start"]);
    repo
}

fn takt(outer: &Path, repo: &Path, test: &str, confinement: &str) -> Command {
    let mut takt = Command::new(env!("CARGO_BIN_EXE_takt"));
    takt.args(["run", "--repo"])
        .arg(repo)
        .args([
            "--intent",
            "probe",
            "--harness",
            "none",
            "--forge",
            "none",
            "--iterations",
            "1",
            "--case-id",
            "probe",
            "--test-cmd",
            test,
            "--confinement",
            confinement,
        ])
        .env("XDG_STATE_HOME", outer.join("state"))
        .env_remove("CARGO_TARGET_DIR");
    takt
}

fn shown(output: &Output) -> String {
    format!(
        "exit {:?}\nstdout {}\nstderr {}",
        output.status.code(),
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    )
}

fn opened(repo: &Path) -> serde_json::Value {
    let events = repo.join(".takt/cases/probe/events.jsonl");
    let text = fs::read_to_string(&events)
        .unwrap_or_else(|error| panic!("{} ({error})", events.display()));
    let line = text
        .lines()
        .find(|line| line.contains("\"event\":\"opened\""))
        .unwrap_or_else(|| panic!("an opened line in {text}"));
    serde_json::from_str(line).expect("json")
}

/// The tightest `file` bound from the cgroup `relative` up to the root, `max` read as none.
fn tightest(relative: &str, file: &str) -> Option<u64> {
    let mut dir = PathBuf::from("/sys/fs/cgroup").join(relative.trim_start_matches('/'));
    let mut bound: Option<u64> = None;
    loop {
        if let Ok(text) = fs::read_to_string(dir.join(file))
            && let Ok(value) = text.trim().parse::<u64>()
        {
            bound = Some(bound.map_or(value, |held| held.min(value)));
        }
        if dir == Path::new("/sys/fs/cgroup") || !dir.pop() {
            return bound;
        }
    }
}

/// On Linux, a `--confinement substrate` test command is held to no looser process and memory
/// bounds than the base's `SubstrateRunner` held it to: at most 2048 processes and 8 GiB.
#[cfg(target_os = "linux")]
#[test]
fn security_substrate_confinement_bounds_no_looser_than_base() {
    let outer = scratch("bounds");
    let lib = r#"#[test]
fn probe() {
    let dir = env!("CARGO_MANIFEST_DIR");
    std::fs::create_dir_all(format!("{dir}/target")).unwrap();
    let cgroup = std::fs::read_to_string("/proc/self/cgroup").unwrap_or_default();
    std::fs::write(format!("{dir}/target/cgroup.part"), cgroup).unwrap();
    std::fs::rename(format!("{dir}/target/cgroup.part"), format!("{dir}/target/cgroup")).unwrap();
    for _ in 0..1200 {
        if std::path::Path::new(&format!("{dir}/target/done")).exists() {
            return;
        }
        std::thread::sleep(std::time::Duration::from_millis(100));
    }
}
"#;
    let repo = repository(
        &outer.0,
        &[
            (
                "Cargo.toml",
                "[package]\nname = \"probe\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n[workspace]\n",
                false,
            ),
            ("src/lib.rs", lib, false),
            ("Cargo.lock", PROBE_LOCK, false),
        ],
    );
    let stdout = outer.0.join("stdout");
    let stderr = outer.0.join("stderr");
    let mut child = takt(&outer.0, &repo, "cargo test --quiet --offline", "substrate")
        .stdout(fs::File::create(&stdout).expect("a file"))
        .stderr(fs::File::create(&stderr).expect("a file"))
        .spawn()
        .expect("takt starts");
    let reported = repo.join("target/cgroup");
    let until = Instant::now() + Duration::from_secs(300);
    while !reported.exists() {
        if let Some(status) = child.try_wait().expect("takt is waited on") {
            let said = fs::read_to_string(&stderr).unwrap_or_default();
            if said.contains("no Substrate adapter on this host serves") {
                eprintln!("skipped: missing prerequisite: {}", said.trim());
                return;
            }
            panic!(
                "takt ended ({status}) before the probe reported its cgroup: {}{said}",
                fs::read_to_string(&stdout).unwrap_or_default()
            );
        }
        assert!(
            Instant::now() < until,
            "the probe reported no cgroup in 300 s"
        );
        std::thread::sleep(Duration::from_millis(100));
    }
    let cgroup = fs::read_to_string(&reported).expect("the probe's cgroup");
    let relative = cgroup.trim().trim_start_matches("0::").to_owned();
    let memory = tightest(&relative, "memory.max");
    let processes = tightest(&relative, "pids.max");
    fs::write(repo.join("target/done"), "").expect("the probe is released");
    let status = child.wait().expect("takt ends");
    let first = fs::read_to_string(&stdout).unwrap_or_default();
    let opened = opened(&repo);
    let shown = format!(
        "cgroup {relative}: memory.max {memory:?}, pids.max {processes:?}; takt {status}: {}; opened {}",
        first.lines().next().unwrap_or_default(),
        opened["substrate"]
    );
    assert!(
        memory.is_some_and(|bytes| bytes <= 8 << 30),
        "security review, story:confinement-through-substrate-on-linux-and-macos: the confined test command's memory bound is looser than the base's 8 GiB: {shown}"
    );
    assert!(
        processes.is_some_and(|count| count <= 2048),
        "security review, story:confinement-through-substrate-on-linux-and-macos: the confined test command's process bound is looser than the base's 2048: {shown}"
    );
}

/// The first line names the adapter and every fact the `opened` event records it proved, as the
/// change's `--confinement` help and its Getting started page say it does.
#[test]
fn security_substrate_confinement_first_line_names_the_proved_facts() {
    let outer = scratch("first-line");
    let repo = repository(&outer.0, &[("check.sh", "#!/bin/sh\nexit 0\n", true)]);
    let output = takt(&outer.0, &repo, "./check.sh", "none")
        .output()
        .expect("takt runs");
    let first = String::from_utf8_lossy(&output.stdout)
        .lines()
        .find(|line| line.starts_with("case "))
        .unwrap_or_default()
        .to_owned();
    let opened = opened(&repo);
    let facts: Vec<String> = opened["substrate"]["facts"]
        .as_array()
        .unwrap_or_else(|| {
            panic!(
                "the opened event records facts: {opened}\n{}",
                shown(&output)
            )
        })
        .iter()
        .filter_map(|fact| fact.as_str().map(str::to_owned))
        .collect();
    assert!(!facts.is_empty(), "local proves facts: {opened}");
    let unnamed: Vec<&String> = facts
        .iter()
        .filter(|fact| !first.contains(fact.as_str()))
        .collect();
    assert!(
        unnamed.is_empty(),
        "security review, story:confinement-through-substrate-on-linux-and-macos: the first line names the adapter and the facts it proved (takt run --help, getting-started.md); it names none of {unnamed:?}: {first}"
    );
}
