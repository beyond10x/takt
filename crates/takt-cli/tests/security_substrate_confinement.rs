//! Security review of story:confinement-through-substrate-on-linux-and-macos (commit 9a93b9de):
//! conformance checks of the guarantees the change claims to keep from its base, 4c2631b6.
//!
//! - The process bounds a `--confinement substrate` test command runs under on Linux are no
//!   looser than the base's: loom-sdk 0.45.0's `SubstrateRunner` held every test command to 2048
//!   processes and 8 GiB of memory (`loom-intake-slice/src/confinement.rs`, `fn limits`).
//! - The first line names the adapter and the facts it proved, as `takt run --help` and
//!   `website/docs/getting-started.md` say it does.

