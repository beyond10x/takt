//! story:confinement-through-substrate-on-linux-and-macos through the binary: every way takt
//! confines a test command is a Substrate adapter.
//!
//! - `--confinement substrate` runs the test command through the first adapter of `systemd`
//!   around `linux`, `linux` and `macos` whose facts serve its profile: the tree the workspace,
//!   the toolchain read-only, the network isolated, nothing of the host outside the tree
//!   readable or writable; the first line and the `opened` event name the adapter and its facts.
//! - A family or fact `--confinement-needs` names that no adapter serves refuses the run by
//!   name before anything starts, under `none` as under `substrate`.
//! - `--confinement none` runs the test command through Substrate's `local` adapter, declared
//!   insecure with the reason the first line and the `opened` event state.
//! - takt's crates hold no confinement mechanism of their own.
//!
//! The confined cases need an adapter of this host; where none serves the run, the case prints
//! `skipped: missing prerequisite: …` with takt's refusal and returns.

use std::fs;
use std::os::unix::fs::PermissionsExt as _;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};

/// A scratch directory under this crate's build directory, removed on drop.
struct Scratch(PathBuf);

impl Drop for Scratch {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

/// An empty scratch directory named for this process and `name`.
fn scratch(name: &str) -> Scratch {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR")).join(format!(
        "confinement-substrate-{}-{name}",
        std::process::id()
    ));
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(&dir).expect("a scratch directory");
    Scratch(dir)
}

/// `git <args>` in `tree`, under an identity of its own.
fn git(tree: &Path, args: &[&str]) {
    let status = Command::new("git")
        .args(["-c", "user.name=t", "-c", "user.email=t@localhost"])
        .args(args)
        .current_dir(tree)
        .status()
        .expect("git runs");
    assert!(status.success(), "git {args:?}");
}

/// The probe crate's lock file as any cargo writes it, committed with the crate: generated by
/// the cargo running these tests it would take in a `[patch]` of whatever `.cargo/config.toml`
/// lies above the scratch directory, which the confined cargo does not see and drops.
const PROBE_LOCK: &str = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"probe\"\nversion = \"0.1.0\"\n";

/// A repository at `outer/repo` holding `files` (path, text, executable), its `target/`
/// ignored, all in one commit.
fn repository(outer: &Path, files: &[(&str, &str, bool)]) -> PathBuf {
    let repo = outer.join("repo");
    fs::create_dir_all(&repo).expect("a directory");
    fs::write(repo.join(".gitignore"), "target/\n").expect("a file");
    for (path, text, executable) in files {
        let at = repo.join(path);
        fs::create_dir_all(at.parent().expect("a parent")).expect("a directory");
        fs::write(&at, text).expect("a file");
        if *executable {
            fs::set_permissions(&at, fs::Permissions::from_mode(0o755)).expect("a mode");
        }
    }
    git(&repo, &["init", "-q", "-b", "main"]);
    git(&repo, &["add", "-A"]);
    git(&repo, &["commit", "-q", "-m", "start"]);
    repo
}

/// `takt run --harness none` on `repo` for one iteration with the test command `test` and
/// `extra` flags, its state under `outer`, `CARGO_TARGET_DIR` and `planted` (a name and value
/// set in takt's environment) as given.
fn takt_run(
    outer: &Path,
    repo: &Path,
    test: &str,
    extra: &[&str],
    planted: &[(&str, &str)],
) -> Output {
    let mut takt = Command::new(env!("CARGO_BIN_EXE_takt"));
    takt.args(["run", "--repo"])
        .arg(repo)
        .args([
            "--intent",
            "probe",
            "--harness",
            "none",
            "--forge",
            "none",
            "--iterations",
            "1",
            "--case-id",
            "probe",
            "--test-cmd",
            test,
        ])
        .args(extra)
        .env("XDG_STATE_HOME", outer.join("state"))
        .env_remove("CARGO_TARGET_DIR");
    for (name, value) in planted {
        takt.env(name, value);
    }
    takt.output().expect("takt runs")
}

/// What `output` printed, for a failure message.
fn shown(output: &Output) -> String {
    format!(
        "exit {:?}\nstdout {}\nstderr {}",
        output.status.code(),
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    )
}

/// The first line `output` printed.
fn first_line(output: &Output) -> String {
    String::from_utf8_lossy(&output.stdout)
        .lines()
        .next()
        .unwrap_or_default()
        .to_owned()
}

/// The `opened` event of the case `probe` on `repo`, wherever under `repo` its record is.
fn opened(repo: &Path) -> serde_json::Value {
    fn find(dir: &Path, into: &mut Vec<PathBuf>) {
        let Ok(entries) = fs::read_dir(dir) else {
            return;
        };
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_dir() {
                find(&path, into);
            } else if path.file_name().is_some_and(|name| name == "events.jsonl") {
                into.push(path);
            }
        }
    }
    let mut found = Vec::new();
    find(&repo.join(".engineering"), &mut found);
    let events = found
        .iter()
        .find_map(|path| fs::read_to_string(path).ok())
        .unwrap_or_else(|| panic!("an events record under {}", repo.display()));
    let line = events
        .lines()
        .find(|line| line.contains("\"event\":\"opened\""))
        .unwrap_or_else(|| panic!("an opened line in {events}"));
    serde_json::from_str(line).expect("json")
}

/// The test of a crate that reports, into its own `target/probe`, the `PATH` it ran on, where
/// its manifest is, what reading `secret` and writing beside it returned, and what connecting
/// to the loopback port `port` returned.
fn probe_test(secret: &Path, port: u16) -> String {
    format!(
        r#"#[test]
fn probe() {{
    let dir = env!("CARGO_MANIFEST_DIR");
    std::fs::create_dir_all(format!("{{dir}}/target")).unwrap();
    let path = std::env::var("PATH").unwrap_or_default();
    let secret = match std::fs::read_to_string("{secret}") {{
        Ok(_) => "read".to_owned(),
        Err(error) => format!("{{:?}}", error.kind()),
    }};
    let outside = match std::fs::write("{secret}.planted", "x") {{
        Ok(()) => "wrote".to_owned(),
        Err(error) => format!("{{:?}}", error.kind()),
    }};
    let net = match std::net::TcpStream::connect(("127.0.0.1", {port})) {{
        Ok(_) => "connected".to_owned(),
        Err(error) => format!("{{:?}}", error.kind()),
    }};
    std::fs::write(
        format!("{{dir}}/target/probe"),
        format!("path {{path}}\nmanifest {{dir}}\nsecret {{secret}}\noutside {{outside}}\nnet {{net}}\n"),
    )
    .unwrap();
}}
"#,
        secret = secret.display()
    )
}

/// What one confined run of a probe crate left: takt's output, the probe's report by key, the
/// `opened` event, and the secret beside the repository the probe tried.
struct Confined {
    output: Output,
    probe: std::collections::BTreeMap<String, String>,
    opened: serde_json::Value,
    secret: PathBuf,
    _outer: Scratch,
}

/// A probe crate's test command run with `--confinement substrate`; `None`, said on stderr,
/// when no adapter of this host serves it.
fn confined_probe(name: &str) -> Option<Confined> {
    let outer = scratch(name);
    let secret = outer.0.join("secret.txt");
    fs::write(&secret, "operator-secret\n").expect("a secret beside the repository");
    let listener = std::net::TcpListener::bind("127.0.0.1:0").expect("a loopback listener");
    listener.set_nonblocking(true).expect("non-blocking");
    let port = listener.local_addr().expect("an address").port();
    let lib = probe_test(&secret, port);
    let repo = repository(
        &outer.0,
        &[
            (
                "Cargo.toml",
                "[package]\nname = \"probe\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n[workspace]\n",
                false,
            ),
            ("src/lib.rs", &lib, false),
            ("Cargo.lock", PROBE_LOCK, false),
        ],
    );
    let output = takt_run(
        &outer.0,
        &repo,
        "cargo test --quiet --offline",
        &["--confinement", "substrate"],
        &[],
    );
    let stderr = String::from_utf8_lossy(&output.stderr);
    if stderr.contains("no Substrate adapter on this host serves") {
        eprintln!("skipped: missing prerequisite: {}", stderr.trim());
        return None;
    }
    let text = fs::read_to_string(repo.join("target/probe"))
        .unwrap_or_else(|error| panic!("the probe reported ({error}): {}", shown(&output)));
    let probe = text
        .lines()
        .filter_map(|line| line.split_once(' '))
        .map(|(key, value)| (key.to_owned(), value.to_owned()))
        .collect();
    assert!(
        listener.accept().is_err(),
        "story:confinement-through-substrate-on-linux-and-macos: the loopback listener took no connection from the confined test: {text}"
    );
    let opened = opened(&repo);
    Some(Confined {
        output,
        probe,
        opened,
        secret,
        _outer: outer,
    })
}

/// What both platforms' confined runs share: the test passed, wrote nothing beside the secret,
/// read none of it, reached no listener, and the opened event names the adapter with its facts.
fn assert_confined(run: &Confined, adapters: &[&str]) {
    let shown = format!("{:?}\n{}", run.probe, shown(&run.output));
    assert!(
        matches!(run.output.status.code(), Some(0 | 3)),
        "story:confinement-through-substrate-on-linux-and-macos: the run ends on its budget or done: {shown}"
    );
    assert_ne!(
        run.probe.get("secret").map(String::as_str),
        Some("read"),
        "story:confinement-through-substrate-on-linux-and-macos: the confined test read a host file outside its tree: {shown}"
    );
    assert_ne!(
        run.probe.get("outside").map(String::as_str),
        Some("wrote"),
        "story:confinement-through-substrate-on-linux-and-macos: the confined test wrote outside its tree: {shown}"
    );
    assert!(
        !run.secret.with_extension("txt.planted").exists(),
        "story:confinement-through-substrate-on-linux-and-macos: nothing planted beside the secret: {shown}"
    );
    assert_ne!(
        run.probe.get("net").map(String::as_str),
        Some("connected"),
        "story:confinement-through-substrate-on-linux-and-macos: the network is isolated: {shown}"
    );
    let adapter = run.opened["substrate"]["adapter"]
        .as_str()
        .unwrap_or_default();
    assert!(
        adapters.contains(&adapter)
            && run.opened["confinement"] == "substrate"
            && run.opened["substrate"].get("declared_insecure").is_none()
            && run.opened["substrate"]["facts"].is_array()
            && run.opened["substrate"]["families"]
                .as_array()
                .is_some_and(|families| families.iter().any(|family| family == "process_run")),
        "story:confinement-through-substrate-on-linux-and-macos: the opened event names the adapter chosen and its facts: {}",
        run.opened
    );
    let first = first_line(&run.output);
    assert!(
        first.contains("; confinement substrate: Substrate ") && first.contains(adapter),
        "story:confinement-through-substrate-on-linux-and-macos: the first line names the adapter: {first}"
    );
}

/// On Linux the test command runs through `systemd` around `linux`, or `linux`: on the fixed
/// `PATH` of the toolchain's read-only root, the tree at `/workspace`.
#[cfg(target_os = "linux")]
#[test]
fn confinement_test_command_confined_linux() {
    let Some(run) = confined_probe("linux") else {
        return;
    };
    assert_confined(&run, &["linux", "systemd"]);
    if run.opened["substrate"]["adapter"] == "systemd" {
        assert_eq!(
            run.opened["substrate"]["inner"], "linux",
            "story:confinement-through-substrate-on-linux-and-macos: systemd wraps linux: {}",
            run.opened
        );
    }
    assert_eq!(
        run.probe.get("path").map(String::as_str),
        Some("/toolchain/rust/bin:/usr/bin:/bin"),
        "story:confinement-through-substrate-on-linux-and-macos: the toolchain is a read-only root: {:?}",
        run.probe
    );
    assert_eq!(
        run.probe.get("manifest").map(String::as_str),
        Some("/workspace"),
        "story:confinement-through-substrate-on-linux-and-macos: the tree is the workspace: {:?}",
        run.probe
    );
}

/// On macOS the test command runs through `macos`, Substrate's Seatbelt profile: at its host
/// path, on the toolchain's `PATH`.
#[cfg(target_os = "macos")]
#[test]
fn confinement_test_command_confined_macos() {
    let run = confined_probe("macos").expect(
        "story:confinement-through-substrate-on-linux-and-macos: Substrate's macos adapter serves a test command on macOS",
    );
    assert_confined(&run, &["macos"]);
    assert!(
        run.probe
            .get("path")
            .is_some_and(|path| path.ends_with("/bin:/usr/bin:/bin")),
        "story:confinement-through-substrate-on-linux-and-macos: the toolchain's PATH: {:?}",
        run.probe
    );
}

/// A repository whose test command, were it ever started, writes `ran` beside it.
fn marking_repository(outer: &Path) -> PathBuf {
    repository(
        outer,
        &[(
            "check.sh",
            &format!(
                "#!/bin/sh\ntouch '{}'\nexit 0\n",
                outer.join("ran").display()
            ),
            true,
        )],
    )
}

/// A family no adapter serves (`network_ingress`), or a name that is no family and no fact,
/// refuses the run before anything starts: exit 1, the name and the refusal said, no case
/// opened and the test command never run; under `none` as under `substrate`.
#[test]
fn confinement_unserved_fact_refused() {
    let outer = scratch("unserved");
    let repo = marking_repository(&outer.0);
    for (confinement, need, said) in [
        ("substrate", "network_ingress", "network_ingress"),
        ("none", "network_ingress", "network_ingress"),
        (
            "substrate",
            "no_such_need",
            "\"no_such_need\" is no contract family and no fact",
        ),
        (
            "none",
            "no_such_need",
            "\"no_such_need\" is no contract family and no fact",
        ),
    ] {
        let output = takt_run(
            &outer.0,
            &repo,
            "./check.sh",
            &["--confinement", confinement, "--confinement-needs", need],
            &[],
        );
        let stderr = String::from_utf8_lossy(&output.stderr);
        assert_eq!(
            output.status.code(),
            Some(1),
            "story:confinement-through-substrate-on-linux-and-macos: {confinement} needing {need} is refused: {}",
            shown(&output)
        );
        assert!(
            stderr.contains(&format!("confinement {confinement} refused the run"))
                && stderr.contains(said)
                && stderr.contains("nothing was started"),
            "story:confinement-through-substrate-on-linux-and-macos: the refusal names {need}: {stderr}"
        );
        assert!(
            !outer.0.join("ran").exists() && !repo.join(".engineering/cases").exists(),
            "story:confinement-through-substrate-on-linux-and-macos: nothing started for {confinement} needing {need}: {}",
            shown(&output)
        );
    }
}

/// `--confinement none` runs the test command through Substrate's `local` adapter, declared
/// insecure: the first line and the `opened` event state the reason; the command's environment
/// is cleared of a credential takt has, and its home and temporary directory are scratch ones.
#[test]
fn confinement_local_is_declared_insecure() {
    let outer = scratch("local");
    let repo = repository(
        &outer.0,
        &[(
            "check.sh",
            "#!/bin/sh\nprintf 'home %s\\ntmp %s\\ntoken %s\\n' \"$HOME\" \"$TMPDIR\" \"$PROBE_API_TOKEN\" > \"$(dirname \"$0\")/../seen\"\nexit 0\n",
            true,
        )],
    );
    let output = takt_run(
        &outer.0,
        &repo,
        "./check.sh",
        &["--confinement", "none"],
        &[
            ("PROBE_API_TOKEN", "planted-token"),
            ("HOME", outer.0.to_str().expect("UTF-8")),
        ],
    );
    let first = first_line(&output);
    assert!(
        first.contains(&format!(
            "; confinement none: Substrate local, declared insecure: {}; proved: ",
            takt::confinement::LOCAL_REASON
        )),
        "story:confinement-through-substrate-on-linux-and-macos: the first line states the reason: {}",
        shown(&output)
    );
    let opened = opened(&repo);
    assert_eq!(
        opened["substrate"]["adapter"], "local",
        "story:confinement-through-substrate-on-linux-and-macos: {opened}"
    );
    assert_eq!(
        opened["substrate"]["declared_insecure"],
        takt::confinement::LOCAL_REASON,
        "story:confinement-through-substrate-on-linux-and-macos: {opened}"
    );
    assert!(
        opened["substrate"]["facts"]
            .as_array()
            .is_some_and(|facts| facts.iter().any(|fact| fact == "declared_insecure")),
        "story:confinement-through-substrate-on-linux-and-macos: local proves declared_insecure: {opened}"
    );
    let seen = fs::read_to_string(outer.0.join("seen"))
        .unwrap_or_else(|error| panic!("the test command ran ({error}): {}", shown(&output)));
    assert!(
        seen.contains("token \n") || seen.ends_with("token "),
        "story:confinement-through-substrate-on-linux-and-macos: no credential reaches the command: {seen}"
    );
    let value = |key: &str| {
        seen.lines()
            .find_map(|line| line.strip_prefix(&format!("{key} ")))
            .unwrap_or_default()
            .to_owned()
    };
    let (home, tmp) = (value("home"), value("tmp"));
    assert!(
        !home.is_empty() && Path::new(&home) != outer.0 && Path::new(&tmp).starts_with(&home),
        "story:confinement-through-substrate-on-linux-and-macos: a scratch home holding TMPDIR: {seen}"
    );
    assert!(
        !Path::new(&home).exists(),
        "story:confinement-through-substrate-on-linux-and-macos: the scratch home is gone after the run: {home}"
    );
}

/// Every file under `dir`, recursively.
fn files(dir: &Path, into: &mut Vec<PathBuf>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            files(&path, into);
        } else {
            into.push(path);
        }
    }
}

/// takt's crates hold no confinement mechanism of their own: no file names Seatbelt's command,
/// the bubblewrap program as a string or a namespace call, the Seatbelt module is gone, and
/// the seam opens Substrate's adapters. The patterns are spelled in parts, so this file does
/// not hold them whole either.
#[test]
fn confinement_no_own_mechanism_left() {
    let crates = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
    let patterns = [
        ["sandbox", "-exec"].concat(),
        format!("\"{}\"", ["bw", "rap"].concat()),
        ["libc::", "unshare"].concat(),
    ];
    let mut found = Vec::new();
    files(&crates, &mut found);
    let held: Vec<String> = found
        .iter()
        .filter_map(|path| {
            let text = fs::read_to_string(path).ok()?;
            let hits: Vec<&String> = patterns
                .iter()
                .filter(|p| text.contains(p.as_str()))
                .collect();
            (!hits.is_empty()).then(|| format!("{}: {hits:?}", path.display()))
        })
        .collect();
    assert!(
        held.is_empty(),
        "story:confinement-through-substrate-on-linux-and-macos: a mechanism of takt's own: {held:?}"
    );
    assert!(
        !crates.join("takt/src/seatbelt.rs").exists(),
        "story:confinement-through-substrate-on-linux-and-macos: takt's Seatbelt module is gone"
    );
    let seam = fs::read_to_string(crates.join("takt/src/confinement.rs")).expect("the seam");
    assert!(
        seam.contains("substrate_host::confinement"),
        "story:confinement-through-substrate-on-linux-and-macos: the seam opens Substrate's adapters"
    );
}
